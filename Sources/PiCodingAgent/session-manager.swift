// MARK: - JSON (Swift-only: upstream writes the entry objects as-is)

extension SessionEntry {
    /// JSON in the key order of the upstream object literal that creates the entry.
    public var json: JsonValue {
        func base(_ type: String, _ id: String, _ parentId: String?, _ timestamp: String) -> JsonObject {
            ["type": .string(type), "id": .string(id), "parentId": parentId.map(JsonValue.string) ?? .null, "timestamp": .string(timestamp)]
        }
        switch self {
        case .message(let e):
            var o = base(e.type, e.id, e.parentId, e.timestamp)
            o["message"] = agentMessageToJson(e.message)
            return .object(o)
        case .thinkingLevelChange(let e):
            var o = base(e.type, e.id, e.parentId, e.timestamp)
            o["thinkingLevel"] = .string(e.thinkingLevel)
            return .object(o)
        case .modelChange(let e):
            var o = base(e.type, e.id, e.parentId, e.timestamp)
            o["provider"] = .string(e.provider)
            o["modelId"] = .string(e.modelId)
            return .object(o)
        case .usage(let e):
            var o = base(e.type, e.id, e.parentId, e.timestamp)
            o["kind"] = .string(e.kind)
            o["provider"] = .string(e.provider)
            o["model"] = .string(e.model)
            o["usage"] = e.usage.json
            if let note = e.note { o["note"] = .string(note) }
            return .object(o)
        case .compaction(let e):
            var o = base(e.type, e.id, e.parentId, e.timestamp)
            o["summary"] = .string(e.summary)
            o["firstKeptEntryId"] = .string(e.firstKeptEntryId)
            o["tokensBefore"] = intJson(e.tokensBefore)
            if let details = e.details { o["details"] = details }
            if let usage = e.usage { o["usage"] = usage.json }
            if let fromHook = e.fromHook { o["fromHook"] = .bool(fromHook) }
            if let systemMessage = e.systemMessage { o["systemMessage"] = systemMessage.json }
            if let firstKeptEntryIndex = e.firstKeptEntryIndex { o["firstKeptEntryIndex"] = intJson(firstKeptEntryIndex) }
            return .object(o)
        case .branchSummary(let e):
            var o = base(e.type, e.id, e.parentId, e.timestamp)
            o["fromId"] = .string(e.fromId)
            o["summary"] = .string(e.summary)
            if let details = e.details { o["details"] = details }
            if let usage = e.usage { o["usage"] = usage.json }
            if let fromHook = e.fromHook { o["fromHook"] = .bool(fromHook) }
            return .object(o)
        case .custom(let e):
            var o: JsonObject = ["type": "custom", "customType": .string(e.customType)]
            if let data = e.data { o["data"] = data }
            o["id"] = .string(e.id)
            o["parentId"] = e.parentId.map(JsonValue.string) ?? .null
            o["timestamp"] = .string(e.timestamp)
            return .object(o)
        case .customMessage(let e):
            var o: JsonObject = ["type": "custom_message", "customType": .string(e.customType)]
            o["content"] = e.content?.json ?? .null
            o["display"] = .bool(e.display)
            if let details = e.details { o["details"] = details }
            o["id"] = .string(e.id)
            o["parentId"] = e.parentId.map(JsonValue.string) ?? .null
            o["timestamp"] = .string(e.timestamp)
            return .object(o)
        case .contextEdit(let e):
            var o = base(e.type, e.id, e.parentId, e.timestamp)
            o["targetId"] = .string(e.targetId)
            o["replacement"] = e.replacement.map { JsonValue.object(["content": $0.content]) } ?? .null
            return .object(o)
        case .label(let e):
            var o = base(e.type, e.id, e.parentId, e.timestamp)
            o["targetId"] = .string(e.targetId)
            if let label = e.label { o["label"] = .string(label) }
            return .object(o)
        case .sessionInfo(let e):
            var o = base(e.type, e.id, e.parentId, e.timestamp)
            if let name = e.name { o["name"] = .string(name) }
            return .object(o)
        case .unknown(let e):
            var o = e.raw
            o["id"] = .string(e.id)
            o["parentId"] = e.parentId.map(JsonValue.string) ?? .null
            return .object(o)
        }
    }

    /// Decode an entry. Session files are parsed without validation upstream: `id`, `parentId` and
    /// `timestamp` may be missing (v1 files); entries that do not decode are kept as `.unknown`.
    public init(object o: JsonObject) {
        let type = o["type"]?.stringValue ?? ""
        let id = o["id"]?.stringValue ?? ""
        let parentId = o["parentId"]?.stringValue
        let timestamp = o["timestamp"]?.stringValue ?? ""
        let unknown = SessionEntry.unknown(UnknownSessionEntry(type: type, id: id, parentId: parentId, timestamp: timestamp, raw: o))
        func usage(_ key: String) -> Usage? { o[key].flatMap { try? Usage(json: $0) } }
        switch type {
        case "message":
            guard let raw = o["message"], var messageObject = raw.objectValue else { self = unknown; return }
            // Session files are parsed without validation; old versions, forks, or
            // hand-edited files can contain messages with null/missing content.
            let role = messageObject["role"]?.stringValue
            if role == "system", messageObject["content"] == nil || messageObject["content"]!.isNull { messageObject["content"] = "" }
            if role == "user" || role == "assistant" || role == "toolResult", messageObject["content"] == nil || messageObject["content"]!.isNull {
                messageObject["content"] = []
            }
            guard let message = try? agentMessageFromJson(.object(messageObject)) else { self = unknown; return }
            self = .message(SessionMessageEntry(id: id, parentId: parentId, timestamp: timestamp, message: message))
        case "thinking_level_change":
            self = .thinkingLevelChange(ThinkingLevelChangeEntry(id: id, parentId: parentId, timestamp: timestamp, thinkingLevel: o["thinkingLevel"]?.stringValue ?? "off"))
        case "model_change":
            self = .modelChange(ModelChangeEntry(id: id, parentId: parentId, timestamp: timestamp, provider: o["provider"]?.stringValue ?? "", modelId: o["modelId"]?.stringValue ?? ""))
        case "usage":
            guard let u = usage("usage") else { self = unknown; return }
            self = .usage(UsageEntry(
                id: id, parentId: parentId, timestamp: timestamp, kind: o["kind"]?.stringValue ?? "", provider: o["provider"]?.stringValue ?? "",
                model: o["model"]?.stringValue ?? "", usage: u, note: o["note"]?.stringValue
            ))
        case "compaction":
            var entry = CompactionEntry(
                id: id, parentId: parentId, timestamp: timestamp, summary: o["summary"]?.stringValue ?? "",
                firstKeptEntryId: o["firstKeptEntryId"]?.stringValue ?? "", tokensBefore: o["tokensBefore"]?.intValue ?? 0,
                details: o["details"], usage: usage("usage"), fromHook: o["fromHook"]?.boolValue,
                systemMessage: o["systemMessage"].flatMap { try? SystemMessage(json: $0) }
            )
            entry.firstKeptEntryIndex = o["firstKeptEntryIndex"]?.intValue
            self = .compaction(entry)
        case "branch_summary":
            self = .branchSummary(BranchSummaryEntry(
                id: id, parentId: parentId, timestamp: timestamp, fromId: o["fromId"]?.stringValue ?? "", summary: o["summary"]?.stringValue ?? "",
                details: o["details"], usage: usage("usage"), fromHook: o["fromHook"]?.boolValue
            ))
        case "custom":
            self = .custom(CustomEntry(id: id, parentId: parentId, timestamp: timestamp, customType: o["customType"]?.stringValue ?? "", data: o["data"]))
        case "custom_message":
            self = .customMessage(CustomMessageEntry(
                id: id, parentId: parentId, timestamp: timestamp, customType: o["customType"]?.stringValue ?? "",
                content: o["content"].flatMap { try? UserMessageContent(json: $0) }, details: o["details"],
                display: o["display"]?.boolValue ?? false
            ))
        case "context_edit":
            let replacement = o["replacement"]?.objectValue.flatMap { r in r["content"].map(ContextEditReplacement.init(content:)) }
            self = .contextEdit(ContextEditEntry(id: id, parentId: parentId, timestamp: timestamp, targetId: o["targetId"]?.stringValue ?? "", replacement: replacement))
        case "label":
            self = .label(LabelEntry(id: id, parentId: parentId, timestamp: timestamp, targetId: o["targetId"]?.stringValue ?? "", label: o["label"]?.stringValue))
        case "session_info":
            self = .sessionInfo(SessionInfoEntry(id: id, parentId: parentId, timestamp: timestamp, name: o["name"]?.stringValue))
        default:
            self = unknown
        }
    }
}

extension FileEntry {
    public var json: JsonValue {
        switch self {
        case .header(let header): return header.json
        case .entry(let entry): return entry.json
        }
    }

    public init(object: JsonObject) {
        if object["type"]?.stringValue == "session" {
            self = .header(SessionHeader(object: object))
        } else {
            self = .entry(SessionEntry(object: object))
        }
    }
}

/** Tree node for getTree() - defensive copy of session structure */
public final class SessionTreeNode: @unchecked Sendable {
    public var entry: SessionEntry
    public var children: [SessionTreeNode]
    /** Resolved label for this entry, if any */
    public var label: String?
    /** Timestamp of the latest label change for this entry, if any */
