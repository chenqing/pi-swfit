    // Branching
    // =========================================================================

    /**
     * Start a new branch from an earlier entry.
     * Moves the leaf pointer to the specified entry. The next appendXXX() call
     * will create a child of that entry, forming a new branch. Existing entries
     * are not modified or deleted.
     */
    public func branch(_ branchFromId: String) throws {
        try locked {
            if byId[branchFromId] == nil {
                throw PiError("Entry \(branchFromId) not found")
            }
            leafId = branchFromId
        }
    }

    /**
     * Reset the leaf pointer to null (before any entries).
     * The next appendXXX() call will create a new root entry (parentId = null).
     * Use this when navigating to re-edit the first user message.
     */
    public func resetLeaf() {
        locked { leafId = nil }
    }

    /**
     * Start a new branch with a summary of the abandoned path.
     * Same as branch(), but also appends a branch_summary entry that captures
     * context from the abandoned conversation path.
     */
    @discardableResult
    public func branchWithSummary(
        _ branchFromId: String?,
        _ summary: String,
        _ details: JsonValue? = nil,
        _ fromHook: Bool? = nil,
        _ usage: Usage? = nil
    ) throws -> String {
        try locked {
            if let branchFromId, byId[branchFromId] == nil {
                throw PiError("Entry \(branchFromId) not found")
            }
            let fromId = leafId ?? "root"
            leafId = branchFromId
            let entry = BranchSummaryEntry(
                id: newEntryId(),
                parentId: branchFromId,
                timestamp: nowIso(),
                fromId: fromId,
                summary: summary,
                details: details,
                usage: usage,
                fromHook: fromHook
            )
            try _appendEntry(.branchSummary(entry))
            return entry.id
        }
    }

    /**
     * Create a new session file containing only the path from root to the specified leaf.
     * Useful for extracting a single conversation path from a branched session.
     * Returns the new session file path, or undefined if not persisting.
     */
    @discardableResult
    public func createBranchedSession(_ leafId: String) throws -> String? {
        try locked {
            let previousSessionFile = sessionFile
            let path = getBranch(leafId)
            if path.isEmpty {
                throw PiError("Entry \(leafId) not found")
            }

            // Filter out LabelEntry from path - we'll recreate them from the resolved map.
            // Because labels are real tree entries, later entries can be children of labels;
            // removing labels requires re-chaining the retained path to avoid orphaned subtrees.
            var pathWithoutLabels: [SessionEntry] = []
            var replacementByLabelId: [String: String] = [:]
            var pendingLabelIds: [String] = []
            var pathParentId: String?
            for entry in path {
                if case .label = entry {
                    pendingLabelIds.append(entry.id)
                    continue
                }
                for labelId in pendingLabelIds {
                    replacementByLabelId[labelId] = entry.id
                }
                pendingLabelIds.removeAll()
                var copy = entry
                copy.parentId = pathParentId
                if case .compaction(var compaction) = copy {
                    compaction.firstKeptEntryId = compaction.firstKeptEntryId == compaction.id
                        ? compaction.id
                        : (replacementByLabelId[compaction.firstKeptEntryId] ?? compaction.firstKeptEntryId)
                    copy = .compaction(compaction)
                }
                pathWithoutLabels.append(copy)
                pathParentId = entry.id
            }

            let newSessionId = createSessionId()
            let timestamp = nowIso()
            let fileTimestamp = String(timestamp.map { $0 == ":" || $0 == "." ? "-" : $0 })
            let newSessionFile = pathJoin(getSessionDir(), "\(fileTimestamp)_\(newSessionId).jsonl")

            let header = SessionHeader(
                version: CURRENT_SESSION_VERSION,
                id: newSessionId,
                timestamp: timestamp,
                cwd: cwd,
                parentSession: persist ? previousSessionFile : nil
            )

            // Collect labels for entries in the path
            var pathEntryIds = Set(pathWithoutLabels.map(\.id))
            var labelsToWrite: [(targetId: String, label: String, timestamp: String)] = []
            // Swift: JS Map iteration order is insertion order; follow the label entries' order.
            var labelOrder: [String] = []
            for fileEntry in fileEntries {
                if case .entry(.label(let label)) = fileEntry {
                    labelOrder.removeAll { $0 == label.targetId }
                    labelOrder.append(label.targetId)
                }
            }
            for targetId in labelOrder {
                guard let label = labelsById[targetId] else { continue }
                if pathEntryIds.contains(targetId) {
                    labelsToWrite.append((targetId, label, labelTimestampsById[targetId]!))
                }
            }

            if persist {
                // Build label entries
                let lastEntryId = pathWithoutLabels.last?.id
                var parentId = lastEntryId
                var labelEntries: [SessionEntry] = []
                for item in labelsToWrite {
                    let ids = pathEntryIds
                    let labelEntry = LabelEntry(
                        id: generateId { ids.contains($0) },
                        parentId: parentId,
                        timestamp: item.timestamp,
                        targetId: item.targetId,
                        label: item.label
                    )
                    pathEntryIds.insert(labelEntry.id)
                    labelEntries.append(.label(labelEntry))
                    parentId = labelEntry.id
                }

                fileEntries = [.header(header)] + pathWithoutLabels.map(FileEntry.entry) + labelEntries.map(FileEntry.entry)
                sessionId = newSessionId
                sessionFile = newSessionFile
                _buildIndex()

                // Use the same rule as _persist(): write now if the branched path already
                // has a conversation, otherwise let _persist() create the file later.
                if _hasConversation() {
                    try _rewriteFile()
                    flushed = true
                } else {
                    flushed = false
                }

                return newSessionFile
            }

            // In-memory mode: replace current session with the path + labels
            var labelEntries: [SessionEntry] = []
            var parentId = pathWithoutLabels.last?.id
            for item in labelsToWrite {
                let ids = pathEntryIds.union(labelEntries.map(\.id))
                let labelEntry = LabelEntry(
                    id: generateId { ids.contains($0) },
                    parentId: parentId,
                    timestamp: item.timestamp,
                    targetId: item.targetId,
                    label: item.label
                )
                labelEntries.append(.label(labelEntry))
                parentId = labelEntry.id
            }
            fileEntries = [.header(header)] + pathWithoutLabels.map(FileEntry.entry) + labelEntries.map(FileEntry.entry)
            sessionId = newSessionId
            _buildIndex()
            return nil
        }
    }

    /**
     * Create a new session.
     * @param cwd Working directory (stored in session header)
     * @param sessionDir Optional session directory. If omitted, uses default (~/.pi/agent/sessions/<encoded-cwd>/).
     */
    public static func create(_ cwd: String, _ sessionDir: String? = nil, _ options: NewSessionOptions? = nil) throws -> SessionManager {
        let dir = sessionDir.map { normalizePath($0) } ?? getDefaultSessionDir(cwd)
        return try SessionManager(cwd, dir, nil, true, options)
    }

    /**
     * Open a specific session file.
     * @param path Path to session file
     * @param sessionDir Optional session directory for /new or /branch. If omitted, derives from file's parent.
     * @param cwdOverride Optional cwd override instead of the session header cwd.
     */
    public static func open(_ path: String, _ sessionDir: String? = nil, _ cwdOverride: String? = nil) throws -> SessionManager {
        let resolvedPath = resolvePath(path)
        var header: SessionHeader?
        var preloadedFileEntries: [FileEntry]?
        if cwdOverride == nil && fileExists(resolvedPath) {
            do {
                header = try readSessionHeader(resolvedPath)
            } catch is SessionHeaderScanLimitError {
                // The bounded scan is only a discovery optimization. A full load remains
                // authoritative for legacy files with very large headers or prefixes.
                preloadedFileEntries = loadEntriesFromFile(resolvedPath)
                header = preloadedFileEntries?.first?.sessionHeader
            }
        }
        let cwd = cwdOverride ?? header.flatMap(getSessionHeaderCwd) ?? FileManager.default.currentDirectoryPath
        // If no sessionDir provided, derive from file's parent directory
        let dir = sessionDir.map { normalizePath($0) } ?? nodeResolvePath(resolvedPath, "..")
        return try SessionManager(cwd, dir, resolvedPath, true, nil, preloadedFileEntries)
    }

    /**
     * Continue the most recent session, or create new if none.
     * @param cwd Working directory
     * @param sessionDir Optional session directory. If omitted, uses default (~/.pi/agent/sessions/<encoded-cwd>/).
     */
    public static func continueRecent(_ cwd: String, _ sessionDir: String? = nil) throws -> SessionManager {
        let dir = sessionDir.map { normalizePath($0) } ?? getDefaultSessionDir(cwd)
        let filterCwd = sessionDir != nil && dir != getDefaultSessionDirPath(cwd)
        if let mostRecent = findMostRecentSession(dir, filterCwd ? cwd : nil) {
            return try SessionManager(cwd, dir, mostRecent, true)
        }
        return try SessionManager(cwd, dir, nil, true)
    }

    /** Create an in-memory session (no file persistence), optionally from entries held outside the filesystem. */
    public static func inMemory(_ cwd: String = FileManager.default.currentDirectoryPath, _ options: NewSessionOptions? = nil, _ entries: [FileEntry]? = nil) throws -> SessionManager {
        try SessionManager(cwd, "", nil, false, options, entries)
    }

    /**
     * Fork a session from another project directory into the current project.
     * Creates a new session in the target cwd with the full history from the source session.
     * @param sourcePath Path to the source session file
     * @param targetCwd Target working directory (where the new session will be stored)
     * @param sessionDir Optional session directory. If omitted, uses default for targetCwd.
     */
    public static func forkFrom(
        _ sourcePath: String,
        _ targetCwd: String,
        _ sessionDir: String? = nil,
        _ options: NewSessionOptions? = nil
    ) throws -> SessionManager {
        let resolvedSourcePath = resolvePath(sourcePath)
        let resolvedTargetCwd = resolvePath(targetCwd)
        let sourceEntries = loadEntriesFromFile(resolvedSourcePath)
        if sourceEntries.isEmpty {
            throw PiError("Cannot fork: source session file is empty or invalid: \(resolvedSourcePath)")
        }

        guard sourceEntries.contains(where: { $0.sessionHeader != nil }) else {
            throw PiError("Cannot fork: source session has no header: \(resolvedSourcePath)")
        }

        let dir = sessionDir.map { normalizePath($0) } ?? getDefaultSessionDir(resolvedTargetCwd)
        if !fileExists(dir) {
            try FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
        }

        // Create new session file with new ID but forked content
        if let id = options?.id {
            try assertValidSessionId(id)
        }
        let newSessionId = options?.id ?? createSessionId()
        let timestamp = toISOString(dateNow())
        let fileTimestamp = String(timestamp.map { $0 == ":" || $0 == "." ? "-" : $0 })
        let newSessionFile = pathJoin(dir, "\(fileTimestamp)_\(newSessionId).jsonl")

        // Write new header pointing to source as parent, with updated cwd
        let newHeader = SessionHeader(
            version: CURRENT_SESSION_VERSION,
            id: newSessionId,
            timestamp: timestamp,
            cwd: resolvedTargetCwd,
            parentSession: resolvedSourcePath
        )
        try writeFileExclusive(newSessionFile, "\(newHeader.json.serialized())\n")

        // Copy all non-header entries from source
        for entry in sourceEntries {
            if case .entry = entry {
                try appendFileSync(newSessionFile, "\(entry.json.serialized())\n")
            }
        }

        return try SessionManager(resolvedTargetCwd, dir, newSessionFile, true)
    }

    /**
     * Find an exact session ID without loading transcript bodies.
     * @param cwd Working directory (used to compute default session directory)
     * @param id Exact session ID
     * @param sessionDir Optional session directory. If omitted, uses default (~/.pi/agent/sessions/<encoded-cwd>/).
     */
    public static func findById(_ cwd: String, _ id: String, _ sessionDir: String? = nil) -> String? {
        let dir = sessionDir.map { normalizePath($0) } ?? getDefaultSessionDir(cwd)
        let filterCwd = sessionDir != nil && dir != getDefaultSessionDirPath(cwd)
        let resolvedCwd = resolvePath(cwd)

        // Exact session discovery is best-effort, matching list().
        guard let files = try? FileManager.default.contentsOfDirectory(atPath: dir) else { return nil }
        for file in files {
            if !file.hasSuffix(".jsonl") { continue }
            let path = pathJoin(dir, file)
            guard let header = readSessionHeaderForDiscovery(path), header.id == id else { continue }
            if filterCwd && !sessionCwdMatches(getSessionHeaderCwd(header), resolvedCwd) { continue }
            return path
        }
        return nil
    }

    /**
     * List all sessions for a directory.
     * @param cwd Working directory (used to compute default session directory)
     * @param sessionDir Optional session directory. If omitted, uses default (~/.pi/agent/sessions/<encoded-cwd>/).
     * @param onProgress Optional callback for progress updates (loaded, total)
     */
    public static func list(
        _ cwd: String,
        _ sessionDir: String? = nil,
        _ onProgress: SessionListProgress? = nil,
        _ signal: AbortSignal? = nil
    ) async throws -> [SessionInfo] {
        let dir = sessionDir.map { normalizePath($0) } ?? getDefaultSessionDir(cwd)
        let filterCwd = sessionDir != nil && dir != getDefaultSessionDirPath(cwd)
        let resolvedCwd = resolvePath(cwd)
        let includeSession: @Sendable (SessionInfo) -> Bool = { session in !filterCwd || sessionCwdMatches(session.cwd, resolvedCwd) }
        var progress: SessionListProgress?
        if let onProgress {
            progress = { (loaded: Int, total: Int, partialSessions: [SessionInfo]?) in
                onProgress(loaded, total, partialSessions?.filter(includeSession))
            }
        }
        let sessions = try await listSessionsFromDir(dir, progress, signal).filter(includeSession)
        return sortSessionInfos(sessions)
    }

    /**
     * List all sessions across all project directories.
     * @param onProgress Optional callback for progress updates (loaded, total)
     */
    public static func listAll(
        _ sessionDir: String? = nil,
        _ onProgress: SessionListProgress? = nil,
        _ signal: AbortSignal? = nil
    ) async throws -> [SessionInfo] {
        let customSessionDir = sessionDir.map { normalizePath($0) }
        let progress = onProgress
        let abortSignal = signal
        try abortSignal?.throwIfAborted()
        if let customSessionDir {
            return sortSessionInfos(try await listSessionsFromDir(customSessionDir, progress, abortSignal))
        }

        let sessionsDir = getSessionsDir()

        do {
            if !fileExists(sessionsDir) { return [] }
            let entries = try FileManager.default.contentsOfDirectory(atPath: sessionsDir)
            let dirs = entries
                .map { pathJoin(sessionsDir, $0) }
                .filter { path in
                    var isDirectory: ObjCBool = false
                    return FileManager.default.fileExists(atPath: path, isDirectory: &isDirectory) && isDirectory.boolValue
                }

            let dirFiles = try await mapWithConcurrency(
                dirs,
                MAX_CONCURRENT_SESSION_DISCOVERY_LOADS,
                { dir, _ in
                    ((try? FileManager.default.contentsOfDirectory(atPath: dir)) ?? [])
                        .filter { $0.hasSuffix(".jsonl") }
                        .map { pathJoin(dir, $0) }
                },
                abortSignal
            )
            let allFiles = dirFiles.flatMap { $0 }
            var candidates = try await mapWithConcurrency(
                allFiles,
                MAX_CONCURRENT_SESSION_DISCOVERY_LOADS,
                { path, _ -> SessionFileCandidate in
                    let mtime = (try? FileManager.default.attributesOfItem(atPath: path))?[.modificationDate] as? Date
                    return SessionFileCandidate(path: path, mtime: mtime)
                },
                abortSignal
            )
            candidates.sort { a, b in
                let ma = a.mtime?.timeIntervalSince1970 ?? -Double.infinity
                let mb = b.mtime?.timeIntervalSince1970 ?? -Double.infinity
                if ma != mb { return ma > mb }
                return pathBasename(a.path) > pathBasename(b.path)
            }

            let totalFiles = candidates.count
            let state = Locked((loaded: 0, firstCandidateLoaded: false, partial: [SessionInfo]()))
            let results = try await buildSessionInfosWithConcurrency(
                candidates,
                { info, index in
                    let (loaded, first, partial) = state.withLock { s -> (Int, Bool, [SessionInfo]) in
                        s.loaded += 1
                        if index == 0 { s.firstCandidateLoaded = true }
                        if let info { s.partial.append(info) }
                        return (s.loaded, s.firstCandidateLoaded, s.partial)
                    }
                    let publishPartial = first && (index == 0 || loaded % ALL_SESSION_LIST_PUBLISH_INTERVAL == 0 || loaded == totalFiles)
                    progress?(loaded, totalFiles, publishPartial ? sortSessionInfos(partial) : nil)
                },
                abortSignal
            )

            return sortSessionInfos(results.compactMap { $0 })
        } catch {
            try abortSignal?.throwIfAborted()
            return []
        }
    }
