    /**
     * Get session header.
     */
    public func getHeader() -> SessionHeader? {
        locked { fileEntries.lazy.compactMap(\.sessionHeader).first }
    }

    /** Number of session entries (excludes header), without copying them like `getEntries()`. */
    public func getEntryCount() -> Int {
        locked { byId.count }
    }

    /**
     * Get all session entries (excludes header). Returns a shallow copy.
     * The session is append-only: use appendXXX() to add entries, branch() to
     * change the leaf pointer. Entries cannot be modified or deleted.
     */
    public func getEntries() -> [SessionEntry] {
        locked { fileEntries.compactMap(\.sessionEntry) }
    }

    /**
     * Get the session as a tree structure. Returns a shallow defensive copy of all entries.
     * A well-formed session has exactly one root (first entry with parentId === null).
     * Orphaned entries (broken parent chain) are also returned as roots.
     */
    public func getTree() -> [SessionTreeNode] {
        locked {
            let entries = getEntries()
            var nodeMap: [String: SessionTreeNode] = [:]
            var roots: [SessionTreeNode] = []

            // Create nodes with resolved labels
            for entry in entries {
                let label = labelsById[entry.id]
                let labelTimestamp = labelTimestampsById[entry.id]
                nodeMap[entry.id] = SessionTreeNode(entry: entry, children: [], label: label, labelTimestamp: labelTimestamp)
            }

            // Build tree
            for entry in entries {
                let node = nodeMap[entry.id]!
                if entry.parentId == nil || entry.parentId == entry.id {
                    roots.append(node)
                } else {
                    if let parent = nodeMap[entry.parentId!] {
                        parent.children.append(node)
                    } else {
                        // Orphan - treat as root
                        roots.append(node)
                    }
                }
            }

            // Sort children by timestamp (oldest first, newest at bottom)
            // Use iterative approach to avoid stack overflow on deep trees
            var stack: [SessionTreeNode] = roots
            while let node = stack.popLast() {
                // Swift: stable sort like Array.prototype.sort; invalid dates compare as equal (NaN upstream).
                node.children = node.children.enumerated().sorted { a, b in
                    let ta = parseIsoTimestamp(a.element.entry.timestamp)
                    let tb = parseIsoTimestamp(b.element.entry.timestamp)
                    if let ta, let tb, ta != tb { return ta < tb }
                    return a.offset < b.offset
                }.map(\.element)
                stack.append(contentsOf: node.children)
            }

            return roots
        }
    }

