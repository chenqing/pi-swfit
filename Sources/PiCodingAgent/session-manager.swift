    _ items: [T],
    _ limit: Int,
    _ map: @escaping @Sendable (T, Int) async throws -> R,
    _ signal: AbortSignal? = nil
) async throws -> [R] {
    var results = [R?](repeating: nil, count: items.count)
    try await withThrowingTaskGroup(of: (Int, R).self) { group in
        var nextIndex = 0
        func addNext() throws {
            try signal?.throwIfAborted()
            let index = nextIndex
            nextIndex += 1
            let item = items[index]
            group.addTask { (index, try await map(item, index)) }
        }
        while nextIndex < min(limit, items.count) { try addNext() }
        while let (index, result) = try await group.next() {
            results[index] = result
            if nextIndex < items.count { try addNext() }
        }
    }
    return results.map { $0! }
}

private func sortSessionInfos(_ sessions: [SessionInfo]) -> [SessionInfo] {
    sessions.sorted { $0.modified > $1.modified }
}

private func buildSessionInfosWithConcurrency(
    _ files: [SessionFileCandidate],
    _ onLoaded: @escaping @Sendable (SessionInfo?, Int) -> Void,
    _ signal: AbortSignal? = nil
) async throws -> [SessionInfo?] {
    try await mapWithConcurrency(
        files,
        MAX_CONCURRENT_SESSION_INFO_LOADS,
        { file, index in
            let info = try await buildSessionInfo(file.path, signal, file.mtime)
            onLoaded(info, index)
            return info
        },
        signal
    )
}

private func listSessionsFromDir(
    _ dir: String,
    _ onProgress: SessionListProgress? = nil,
    _ signal: AbortSignal? = nil
) async throws -> [SessionInfo] {
    try signal?.throwIfAborted()
    if !fileExists(dir) { return [] }

    do {
        let dirEntries = try FileManager.default.contentsOfDirectory(atPath: dir)
        let files = dirEntries
            .filter { $0.hasSuffix(".jsonl") }
            .sorted { $0 > $1 }
            .map { SessionFileCandidate(path: pathJoin(dir, $0)) }
        let total = files.count
        let state = Locked((loaded: 0, partial: [SessionInfo]()))
        let results = try await buildSessionInfosWithConcurrency(
            files,
            { info, _ in
                let (loaded, partial) = state.withLock { s -> (Int, [SessionInfo]) in
                    s.loaded += 1
                    if let info { s.partial.append(info) }
                    return (s.loaded, s.partial)
                }
                let publishPartial = loaded == 1 || loaded % CURRENT_SESSION_LIST_PUBLISH_INTERVAL == 0 || loaded == total
                onProgress?(loaded, total, publishPartial ? sortSessionInfos(partial) : nil)
            },
            signal
        )
        return results.compactMap { $0 }
    } catch {
        try signal?.throwIfAborted()
        return []
    }
}

/**
 * Manages conversation sessions as append-only trees stored in JSONL files.
 *
 * Each session entry has an id and parentId forming a tree structure. The "leaf"
 * pointer tracks the current position. Appending creates a child of the current leaf.
 * Branching moves the leaf to an earlier entry, allowing new branches without
 * modifying history.
 *
 * Use buildSessionContext() to get the resolved message list for the LLM, which
 * handles compaction summaries and follows the path from root to current leaf.
 *
 * Swift: state is guarded by a recursive lock so the manager can be shared with `AgentSession`.
 */
public final class SessionManager: @unchecked Sendable {
    private let lock = NSRecursiveLock()
    private var sessionId: String = ""
    private var sessionFile: String?
    private var sessionDir: String
    private var cwd: String
    private var persist: Bool
    private var flushed: Bool = false
    private var fileEntries: [FileEntry] = []
    private var byId: [String: SessionEntry] = [:]
    /// Swift: insertion order of `byId` (JS `Map` iteration order).
    private var byIdOrder: [String] = []
    private var labelsById: [String: String] = [:]
    private var labelTimestampsById: [String: String] = [:]
    private var leafId: String?

    private func locked<T>(_ body: () throws -> T) rethrows -> T {
        lock.lock()
        defer { lock.unlock() }
        return try body()
    }

    private init(
        _ cwd: String,
        _ sessionDir: String,
        _ sessionFile: String?,
        _ persist: Bool,
        _ newSessionOptions: NewSessionOptions? = nil,
        _ preloadedFileEntries: [FileEntry]? = nil
    ) throws {
        self.cwd = resolvePath(cwd)
        self.sessionDir = sessionDir.isEmpty ? "" : normalizePath(sessionDir)
        self.persist = persist
        if persist && !self.sessionDir.isEmpty && !fileExists(self.sessionDir) {
            try FileManager.default.createDirectory(atPath: self.sessionDir, withIntermediateDirectories: true)
        }

        if let sessionFile, !sessionFile.isEmpty {
            try _setSessionFile(sessionFile, preloadedFileEntries)
        } else if let preloadedFileEntries, !preloadedFileEntries.isEmpty {
            try _loadEntries(preloadedFileEntries, newSessionOptions)
        } else {
            _ = try newSession(newSessionOptions)
        }
    }

    /** Switch to a different session file (used for resume and branching) */
    public func setSessionFile(_ sessionFile: String) throws {
        try locked { try _setSessionFile(sessionFile) }
    }

    private func _setSessionFile(_ sessionFile: String, _ preloadedFileEntries: [FileEntry]? = nil) throws {
        self.sessionFile = resolvePath(sessionFile)
        if fileExists(self.sessionFile!) {
            let entries = preloadedFileEntries ?? loadEntriesFromFile(self.sessionFile!)

            // If file was empty, initialize it with a valid session header. If it was
            // non-empty but did not parse as a pi session, fail without modifying it.
            if entries.isEmpty {
                let explicitPath = self.sessionFile!
                let size = ((try? FileManager.default.attributesOfItem(atPath: explicitPath))?[.size] as? NSNumber)?.intValue ?? 0
                if size > 0 {
                    throw PiError("Session file is not a valid \(APP_NAME) session: \(explicitPath)")
                }
                _ = try newSession()
                self.sessionFile = explicitPath
                try _rewriteFile()
                flushed = true
                return
            }

            try _loadEntries(entries)
            flushed = true
        } else {
            let explicitPath = self.sessionFile!
            _ = try newSession()
            self.sessionFile = explicitPath // preserve explicit path from --session flag
        }
    }

    @discardableResult
    public func newSession(_ options: NewSessionOptions? = nil) throws -> String? {
        try locked {
            if let id = options?.id {
                try assertValidSessionId(id)
            }
            sessionId = options?.id ?? createSessionId()
            let timestamp = toISOString(dateNow())
            let header = SessionHeader(
                version: CURRENT_SESSION_VERSION,
                id: sessionId,
                timestamp: timestamp,
                cwd: cwd,
                parentSession: options?.parentSession
            )
            fileEntries = [.header(header)]
            byId.removeAll()
            byIdOrder.removeAll()
            labelsById.removeAll()
            labelTimestampsById.removeAll()
            leafId = nil
            flushed = false

            if persist {
                let fileTimestamp = String(timestamp.map { $0 == ":" || $0 == "." ? "-" : $0 })
                sessionFile = pathJoin(getSessionDir(), "\(fileTimestamp)_\(sessionId).jsonl")
            }
            return sessionFile
        }
    }

    private func _loadEntries(_ entries: [FileEntry], _ options: NewSessionOptions? = nil) throws {
        let header = entries.lazy.compactMap(\.sessionHeader).first

        if let header {
            fileEntries = entries
            sessionId = header.id

            if migrateToCurrentVersion(&fileEntries) {
                try _rewriteFile()
            }
        } else {
            _ = try newSession(options)
            fileEntries = fileEntries + entries
        }

        _buildIndex()
    }

    private func setById(_ entry: SessionEntry) {
        if byId[entry.id] == nil { byIdOrder.append(entry.id) }
        byId[entry.id] = entry
    }

    private func _buildIndex() {
        byId.removeAll()
        byIdOrder.removeAll()
        labelsById.removeAll()
        labelTimestampsById.removeAll()
        leafId = nil
        for fileEntry in fileEntries {
            guard case .entry(let entry) = fileEntry else { continue }
            setById(entry)
            leafId = entry.id
            if case .label(let label) = entry {
                if let text = label.label, !text.isEmpty {
                    labelsById[label.targetId] = text
                    labelTimestampsById[label.targetId] = label.timestamp
                } else {
                    labelsById.removeValue(forKey: label.targetId)
                    labelTimestampsById.removeValue(forKey: label.targetId)
                }
            }
        }
    }

    private func _rewriteFile() throws {
        guard persist, let sessionFile else { return }
        var text = ""
        for entry in fileEntries {
            text += "\(entry.json.serialized())\n"
        }
        try writeFileTruncating(sessionFile, text)
    }

    public func isPersisted() -> Bool {
        locked { persist }
    }

    public func getCwd() -> String {
        locked { cwd }
    }

    public func getSessionDir() -> String {
        locked { sessionDir }
    }

    public func usesDefaultSessionDir() -> Bool {
        locked { sessionDir == getDefaultSessionDirPath(cwd) }
    }

    public func getSessionId() -> String {
        locked { sessionId }
    }

    public func getSessionFile() -> String? {
        locked { sessionFile }
    }

    /**
     * A new session file is created only once the session contains a user or assistant message.
     * Setup entries alone (model, thinking level, system prompt) stay in memory so opening and
     * closing pi without chatting leaves no file behind. Starting at the user message (not the
     * first assistant reply) keeps the prompt on disk if the first turn never completes (#10000).
     */
    private func _hasConversation() -> Bool {
        fileEntries.contains { entry in
            guard case .entry(.message(let e)) = entry else { return false }
            return e.message.role == "user" || e.message.role == "assistant"
        }
    }

    public func _persist(_ entry: SessionEntry) throws {
        try locked {
            guard persist, let sessionFile else { return }

            if !flushed {
                if !_hasConversation() { return }
                var text = ""
                for e in fileEntries {
                    text += "\(e.json.serialized())\n"
                }
                try writeFileExclusive(sessionFile, text)
                flushed = true
            } else {
                try appendFileSync(sessionFile, "\(entry.json.serialized())\n")
            }
        }
    }

    private func _appendEntry(_ entry: SessionEntry) throws {
        // Upstream 807a5c051: a failed write must not become the parent of later entries.
        let previousLeafId = leafId
        fileEntries.append(.entry(entry))
        setById(entry)
        leafId = entry.id
        do { try _persist(entry) }
        catch {
            fileEntries.removeLast()
            byId.removeValue(forKey: entry.id)
            leafId = previousLeafId
            throw error
        }
    }

    private func newEntryId() -> String {
        generateId { byId[$0] != nil }
    }

    private func nowIso() -> String { toISOString(dateNow()) }

    /** Append a message as child of current leaf, then advance leaf. Returns entry id.
     * Does not allow writing CompactionSummaryMessage and BranchSummaryMessage directly.
     * Reason: we want these to be top-level entries in the session, not message session entries,
     * so it is easier to find them.
     * These need to be appended via appendCompaction() and appendBranchSummary() methods.
     */
    @discardableResult
    public func appendMessage(_ message: AgentMessage) throws -> String {
        try locked {
            let entry = SessionMessageEntry(
                id: newEntryId(),
                parentId: leafId,
                timestamp: nowIso(),
                message: message
            )
            try _appendEntry(.message(entry))
            return entry.id
        }
    }

    @discardableResult
    public func appendMessage(_ message: Message) throws -> String { try appendMessage(AgentMessage(message)) }
    @discardableResult
    public func appendMessage(_ message: CustomMessage) throws -> String { try appendMessage(message.agentMessage) }
    @discardableResult
    public func appendMessage(_ message: BashExecutionMessage) throws -> String { try appendMessage(message.agentMessage) }

