    /** Append a compaction summary as child of current leaf, then advance leaf. Returns entry id. */
    @discardableResult
    public func appendCompaction(
        _ summary: String,
        _ firstKeptEntryId: String?,
        _ tokensBefore: Int,
        _ details: JsonValue? = nil,
        _ fromHook: Bool? = nil,
        _ usage: Usage? = nil
    ) throws -> String {
        try locked {
            let timestampMs = dateNow()
            let timestamp = toISOString(timestampMs)
            let systemMessage = getCurrentSystemMessage(buildSessionProjection().messages.compactMap(\.llmMessage))
            let id = newEntryId()
            var entry = CompactionEntry(
                id: id,
                parentId: leafId,
                timestamp: timestamp,
                summary: summary,
                firstKeptEntryId: firstKeptEntryId ?? id,
                tokensBefore: tokensBefore,
                details: details,
                usage: usage,
                fromHook: fromHook
            )
            if var systemMessage {
                systemMessage.timestamp = parseIsoTimestamp(timestamp) ?? timestampMs
                entry.systemMessage = systemMessage
            }
            try _appendEntry(.compaction(entry))
            return entry.id
        }
    }

