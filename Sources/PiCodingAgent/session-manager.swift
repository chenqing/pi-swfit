private let SESSION_READ_BUFFER_SIZE = 1024 * 1024
private let SESSION_HEADER_READ_BUFFER_SIZE = 4096
/** Bound synchronous header discovery while allowing large cwd and custom metadata fields. */
private let MAX_SESSION_HEADER_SCAN_BYTES = 1024 * 1024

struct SessionHeaderScanLimitError: Error, CustomStringConvertible, LocalizedError {
    let filePath: String
    var name: String { "SessionHeaderScanLimitError" }
    var description: String { "Session header exceeds \(MAX_SESSION_HEADER_SCAN_BYTES)-byte scan limit: \(filePath)" }
    var errorDescription: String? { description }
}

private func parseSessionEntryObject(_ line: String) -> JsonObject? {
    if line.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return nil }
    // Skip malformed lines
    guard let value = try? JsonValue.parse(line) else { return nil }
    // Swift: upstream accepts any JSON value; only objects can be entries.
    return value.objectValue
}

private func parseSessionEntryLine(_ line: String) -> FileEntry? {
    parseSessionEntryObject(line).map(FileEntry.init(object:))
}

/// Swift-only file helpers (`fs` sync APIs).
private func fileExists(_ path: String) -> Bool { FileManager.default.fileExists(atPath: path) }

private func appendFileSync(_ path: String, _ text: String) throws {
    let data = Data(text.utf8)
    if let handle = FileHandle(forWritingAtPath: path) {
        defer { try? handle.close() }
        try handle.seekToEnd()
        try handle.write(contentsOf: data)
    } else {
        guard FileManager.default.createFile(atPath: path, contents: data) else {
            throw PiError("ENOENT: no such file or directory, open '\(path)'")
        }
    }
}

/// `openSync(path, "wx")` + writes: fails if the file exists.
private func writeFileExclusive(_ path: String, _ text: String) throws {
    let fd = open(path, O_WRONLY | O_CREAT | O_EXCL, 0o644)
    if fd < 0 {
        if errno == EEXIST { throw PiError("EEXIST: file already exists, open '\(path)'") }
        throw PiError("ENOENT: no such file or directory, open '\(path)'")
    }
    let handle = FileHandle(fileDescriptor: fd, closeOnDealloc: true)
    try handle.write(contentsOf: Data(text.utf8))
    try handle.close()
}

/// `openSync(path, "w")` + writes.
private func writeFileTruncating(_ path: String, _ text: String) throws {
    try Data(text.utf8).write(to: URL(fileURLWithPath: path))
}

/** Exported for testing */
public func loadEntriesFromFile(_ filePath: String) -> [FileEntry] {
    let resolvedFilePath = normalizePath(filePath)
    if !fileExists(resolvedFilePath) { return [] }
    guard let data = FileManager.default.contents(atPath: resolvedFilePath) else { return [] }
    // Swift: reads the whole file at once (upstream streams SESSION_READ_BUFFER_SIZE chunks with a StringDecoder).
    _ = SESSION_READ_BUFFER_SIZE
    let text = String(decoding: data, as: UTF8.self)

    var entries: [FileEntry] = []
    var objects: [JsonObject] = []
    var lines = text.components(separatedBy: "\n")
    let pending = lines.removeLast()
    for line in lines {
        if let object = parseSessionEntryObject(line) { objects.append(object) }
    }
    if let finalObject = parseSessionEntryObject(pending) { objects.append(finalObject) }

    // Validate session header before repairing the file.
    if objects.isEmpty { return entries }
    let header = objects[0]
    if header["type"]?.stringValue != "session" || header["id"]?.stringValue == nil {
        return []
    }
    entries = objects.map(FileEntry.init(object:))

    if !pending.isEmpty { try? appendFileSync(resolvedFilePath, "\n") }
    return entries
}

/**
 * Inspect a physical line while searching for the first parsed session entry.
 * Blank and malformed lines are skipped to match loadEntriesFromFile().
 * Returns undefined to keep scanning, null for a parsed non-header entry, or the header.
 */
private func parseSessionHeaderCandidate(_ line: String) -> SessionHeader?? {
    if line.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .none }
    guard let entry = parseSessionEntryObject(line) else { return .none }
    if entry["type"]?.stringValue != "session" || entry["id"]?.stringValue == nil { return .some(nil) }
    return .some(SessionHeader(object: entry))
}

func readSessionHeader(_ filePath: String) throws -> SessionHeader? {
    guard let handle = FileHandle(forReadingAtPath: filePath) else {
        throw PiError("ENOENT: no such file or directory, open '\(filePath)'")
    }
    defer { try? handle.close() }
    _ = SESSION_HEADER_READ_BUFFER_SIZE
    let data = try handle.read(upToCount: MAX_SESSION_HEADER_SCAN_BYTES) ?? Data()
    var lineStart = data.startIndex
    var index = data.startIndex
    while index < data.endIndex {
        if data[index] == 0x0A {
            let line = String(decoding: data[lineStart..<index], as: UTF8.self)
            if let header = parseSessionHeaderCandidate(line) { return header }
            lineStart = index + 1
        }
        index += 1
    }
    let tail = String(decoding: data[lineStart..<data.endIndex], as: UTF8.self)
    if data.count < MAX_SESSION_HEADER_SCAN_BYTES {
        return parseSessionHeaderCandidate(tail) ?? nil
    }

    // Probe for EOF so a final header without a newline is allowed when it ends
    // exactly at the scan limit. Any additional byte exceeds the bounded scan.
    let probe = try handle.read(upToCount: 1) ?? Data()
    if probe.isEmpty {
        return parseSessionHeaderCandidate(tail) ?? nil
    }
    throw SessionHeaderScanLimitError(filePath: filePath)
}

private func readSessionHeaderForDiscovery(_ filePath: String) -> SessionHeader? {
    do {
        return try readSessionHeader(filePath)
    } catch {
        // Discovery is best-effort: unreadable or oversized files are not sessions,
        // and one corrupt file must not prevent other sessions from being found.
        return nil
    }
}

private func getSessionHeaderCwd(_ header: SessionHeader) -> String? {
    // Swift: a missing or non-string cwd decodes as "", which no caller treats as a usable cwd.
    header.cwd.isEmpty ? nil : header.cwd
}

private func sessionCwdMatches(_ cwd: String?, _ resolvedCwd: String) -> Bool {
    guard let cwd, !cwd.isEmpty else { return false }
    return resolvePath(cwd) == resolvedCwd
}

private func fileMtimeMs(_ path: String) -> Double? {
    guard let attrs = try? FileManager.default.attributesOfItem(atPath: path),
          let date = attrs[.modificationDate] as? Date else { return nil }
    return date.timeIntervalSince1970 * 1000
}

/** Exported for testing */
public func findMostRecentSession(_ sessionDir: String, _ cwd: String? = nil) -> String? {
    let resolvedSessionDir = normalizePath(sessionDir)
    let resolvedCwd = cwd.map { resolvePath($0) }
    guard let names = try? FileManager.default.contentsOfDirectory(atPath: resolvedSessionDir) else {
        // Directory access and stat races make recent-session discovery unavailable.
        return nil
    }
    var files: [(path: String, mtime: Double)] = []
    for file in names where file.hasSuffix(".jsonl") {
        let path = pathJoin(resolvedSessionDir, file)
        guard let mtime = fileMtimeMs(path) else { return nil }
        files.append((path, mtime))
    }
    files.sort { $0.mtime > $1.mtime }

    for (path, _) in files {
        let header = readSessionHeaderForDiscovery(path)
        if let header, resolvedCwd == nil || sessionCwdMatches(getSessionHeaderCwd(header), resolvedCwd!) { return path }
    }
    return nil
}

private func isMessageWithContent(_ message: AgentMessage) -> Message? {
    message.llmMessage
}

private func extractTextContent(_ message: Message) -> String {
    switch message {
    case .user(let m):
        switch m.content {
        case .string(let text): return text
        case .blocks(let blocks): return blocks.compactMap { $0.textContent?.text }.joined(separator: " ")
        }
    case .assistant(let m):
        return m.content.compactMap { $0.textContent?.text }.joined(separator: " ")
    case .system(let m):
        switch m.content {
        case .string(let text): return text
        case .blocks(let blocks): return blocks.map(\.text).joined(separator: " ")
        }
    case .toolResult(let m):
        return m.content.compactMap { $0.textContent?.text }.joined(separator: " ")
    }
}

private func getMessageActivityTime(_ entry: SessionMessageEntry) -> Int? {
    guard let message = isMessageWithContent(entry.message) else { return nil }
    if message.role != "user" && message.role != "assistant" { return nil }
    // Swift: decoded messages always carry a numeric timestamp.
    return message.timestamp
}

private func buildSessionInfo(_ filePath: String, _ signal: AbortSignal? = nil, _ fileMtime: Date? = nil) async throws -> SessionInfo? {
    guard let data = FileManager.default.contents(atPath: filePath) else {
        try signal?.throwIfAborted()
        return nil
    }
    let mtime = fileMtime ?? ((try? FileManager.default.attributesOfItem(atPath: filePath))?[.modificationDate] as? Date) ?? Date()
    var header: SessionHeader?
    var messageCount = 0
    var firstMessage = ""
    var allMessages: [String] = []
    var name: String?
    var lastActivityTime: Int?

    let text = String(decoding: data, as: UTF8.self)
    for rawLine in text.components(separatedBy: "\n") {
        try signal?.throwIfAborted()
        let line = rawLine.hasSuffix("\r") ? String(rawLine.dropLast()) : rawLine
        guard let entry = parseSessionEntryLine(line) else { continue }

        if header == nil {
            guard case .header(let h) = entry else { return nil }
            header = h
            continue
        }

        // Extract session name (use latest, including explicit clears)
        if case .entry(.sessionInfo(let info)) = entry {
            let trimmed = info.name?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
            name = trimmed.isEmpty ? nil : trimmed
        }

        guard case .entry(.message(let messageEntry)) = entry else { continue }
        messageCount += 1

        if let activityTime = getMessageActivityTime(messageEntry) {
            lastActivityTime = max(lastActivityTime ?? 0, activityTime)
        }

        guard let message = isMessageWithContent(messageEntry.message) else { continue }
        if message.role != "user" && message.role != "assistant" { continue }

        let textContent = extractTextContent(message)
        if textContent.isEmpty { continue }

        allMessages.append(textContent)
        if firstMessage.isEmpty && message.role == "user" {
            firstMessage = textContent
        }
    }

    guard let header else { return nil }

    let cwd = header.cwd
    let parentSessionPath = header.parentSession
    let headerTime = parseIsoTimestamp(header.timestamp)
    let modified: Date
    if let lastActivityTime, lastActivityTime > 0 {
        modified = Date(timeIntervalSince1970: Double(lastActivityTime) / 1000)
    } else if let headerTime {
        modified = Date(timeIntervalSince1970: Double(headerTime) / 1000)
    } else {
        modified = mtime
    }

    return SessionInfo(
        path: filePath,
        id: header.id,
        cwd: cwd,
        name: name,
        parentSessionPath: parentSessionPath,
        created: Date(timeIntervalSince1970: Double(headerTime ?? 0) / 1000),
        modified: modified,
        messageCount: messageCount,
        firstMessage: firstMessage.isEmpty ? "(no messages)" : firstMessage,
        allMessagesText: allMessages.joined(separator: " ")
    )
}

