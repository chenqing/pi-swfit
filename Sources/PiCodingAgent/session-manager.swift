private func randomUUID() -> String { UUID().uuidString.lowercased() }

/** Generate a unique short ID (8 hex chars, collision-checked) */
private func generateId(_ has: (String) -> Bool) -> String {
    for _ in 0..<100 {
        let id = String(randomUUID().prefix(8))
        if !has(id) { return id }
    }
    // Fallback to full UUID if somehow we have collisions
    return randomUUID()
}

/** Migrate v1 → v2: add id/parentId tree structure. Mutates in place. */
private func migrateV1ToV2(_ entries: inout [FileEntry]) {
    let ids = Set<String>()
    var prevId: String?

    for index in entries.indices {
        if case .header(var header) = entries[index] {
            header.version = 2
            entries[index] = .header(header)
            continue
        }
        guard case .entry(var entry) = entries[index] else { continue }

        entry.id = generateId { ids.contains($0) }
        entry.parentId = prevId
        prevId = entry.id

        // Convert firstKeptEntryIndex to firstKeptEntryId for compaction
        if case .compaction(var comp) = entry {
            if let firstKeptEntryIndex = comp.firstKeptEntryIndex {
                if firstKeptEntryIndex >= 0, firstKeptEntryIndex < entries.count, case .entry(let targetEntry) = entries[firstKeptEntryIndex] {
                    comp.firstKeptEntryId = targetEntry.id
                }
                comp.firstKeptEntryIndex = nil
            }
            entry = .compaction(comp)
        }
        entries[index] = .entry(entry)
    }
}

/** Migrate v2 → v3: rename hookMessage role to custom. Mutates in place. */
private func migrateV2ToV3(_ entries: inout [FileEntry]) {
    for index in entries.indices {
        if case .header(var header) = entries[index] {
            header.version = 3
            entries[index] = .header(header)
            continue
        }

        // Update message entries with hookMessage role
        if case .entry(.message(var msgEntry)) = entries[index] {
            if case .custom(var custom) = msgEntry.message, custom.role == "hookMessage" {
                custom.role = "custom"
                msgEntry.message = .custom(custom)
                entries[index] = .entry(.message(msgEntry))
            }
        }
    }
}

/**
 * Run all necessary migrations to bring entries to current version.
 * Mutates entries in place. Returns true if any migration was applied.
 */
private func migrateToCurrentVersion(_ entries: inout [FileEntry]) -> Bool {
    let header = entries.lazy.compactMap(\.sessionHeader).first
    let version = header?.version ?? 1

    if version >= CURRENT_SESSION_VERSION { return false }

    if version < 2 { migrateV1ToV2(&entries) }
    if version < 3 { migrateV2ToV3(&entries) }

    return true
}

