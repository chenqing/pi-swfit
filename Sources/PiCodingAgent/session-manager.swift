private func intJson(_ value: Int) -> JsonValue { .number(Double(value)) }

public struct SessionHeader: Sendable {
    public var type: String { "session" }
    public var version: Int? // v1 sessions don't have this
    public var id: String
    public var timestamp: String
    public var cwd: String
    public var parentSession: String?
    /// Swift-only: fields upstream keeps untouched on the parsed object (e.g. legacy `provider`, `branchedFrom`).
    public var extra: JsonObject
    public init(version: Int? = nil, id: String, timestamp: String, cwd: String, parentSession: String? = nil, extra: JsonObject = JsonObject()) {
        self.version = version; self.id = id; self.timestamp = timestamp; self.cwd = cwd; self.parentSession = parentSession; self.extra = extra
    }

    public var json: JsonValue {
        var o: JsonObject = ["type": "session"]
        if let version { o["version"] = intJson(version) }
        o["id"] = .string(id)
        o["timestamp"] = .string(timestamp)
        o["cwd"] = .string(cwd)
        if let parentSession { o["parentSession"] = .string(parentSession) }
        for (key, value) in extra where o[key] == nil { o[key] = value }
        return .object(o)
    }

    init(object o: JsonObject) {
        var extra = JsonObject()
        for (key, value) in o where !["type", "version", "id", "timestamp", "cwd", "parentSession"].contains(key) { extra[key] = value }
        self.init(
            version: o["version"]?.intValue, id: o["id"]?.stringValue ?? "", timestamp: o["timestamp"]?.stringValue ?? "",
            cwd: o["cwd"]?.stringValue ?? "", parentSession: o["parentSession"]?.stringValue, extra: extra
        )
    }
}

