    public func getChildren(_ parentId: String) -> [SessionEntry] {
        locked {
            var children: [SessionEntry] = []
            for id in byIdOrder {
                guard let entry = byId[id] else { continue }
                if entry.parentId == parentId {
                    children.append(entry)
                }
            }
            return children
        }
    }

    /**
     * Get the label for an entry, if any.
     */
    public func getLabel(_ id: String) -> String? {
        locked { labelsById[id] }
    }

    /**
     * Set or clear a label on an entry.
     * Labels are user-defined markers for bookmarking/navigation.
     * Pass undefined or empty string to clear the label.
     */
    @discardableResult
    public func appendLabelChange(_ targetId: String, _ label: String?) throws -> String {
        try locked {
            if byId[targetId] == nil {
                throw PiError("Entry \(targetId) not found")
            }
            let entry = LabelEntry(
                id: newEntryId(),
                parentId: leafId,
                timestamp: nowIso(),
                targetId: targetId,
                label: label
            )
            try _appendEntry(.label(entry))
            if let label, !label.isEmpty {
                labelsById[targetId] = label
                labelTimestampsById[targetId] = entry.timestamp
            } else {
                labelsById.removeValue(forKey: targetId)
                labelTimestampsById.removeValue(forKey: targetId)
            }
            return entry.id
        }
    }

    /**
     * Walk from entry to root, returning all entries in path order.
     * Includes all entry types (messages, compaction, model changes, etc.).
     * Use buildSessionContext() to get the resolved messages for the LLM.
     */
    public func getBranch(_ fromId: String? = nil) -> [SessionEntry] {
        locked {
            var path: [SessionEntry] = []
            let startId = fromId ?? leafId
            var current = startId.flatMap { $0.isEmpty ? nil : byId[$0] }
            while let entry = current {
                path.append(entry)
                current = entry.parentId.flatMap { $0.isEmpty ? nil : byId[$0] }
            }
            path.reverse()
            return path
        }
    }

