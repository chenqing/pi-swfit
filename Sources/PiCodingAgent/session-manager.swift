    /** Append a branch-local edit to an earlier model-visible entry. */
    @discardableResult
    public func appendContextEdit(_ targetId: String, _ replacement: ContextEditReplacement?) throws -> String {
        try locked {
            if let replacement {
                switch replacement.content {
                case .string, .array: break
                default: throw PiError("Context edit replacement must be null or contain string/array content")
                }
            }
            guard let target = byId[targetId] else { throw PiError("Entry \(targetId) not found") }
            if !getBranch().contains(where: { $0.id == targetId }) {
                throw PiError("Entry \(targetId) is not on the active branch")
            }
            var editable = false
            var targetRole = "custom"
            if case .customMessage = target { editable = true }
            if case .message(let e) = target {
                targetRole = e.message.role
                editable = targetRole == "user" || targetRole == "assistant" || targetRole == "toolResult"
            }
            if !editable { throw PiError("Entry \(targetId) does not contribute editable model content") }
            var normalizedReplacement = replacement
            if let replacement, targetRole == "assistant" || targetRole == "toolResult", case .string(let text) = replacement.content {
                normalizedReplacement = ContextEditReplacement(content: [["type": "text", "text": .string(text)]])
            }
            let entry = ContextEditEntry(
                id: newEntryId(),
                parentId: leafId,
                timestamp: nowIso(),
                targetId: targetId,
                replacement: normalizedReplacement
            )
            try _appendEntry(.contextEdit(entry))
            return entry.id
        }
    }

