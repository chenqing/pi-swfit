public func oauthSuccessHtml(_ message: String) -> String {
    renderPage(
        title: "Authentication successful",
        heading: "Authentication successful",
        message: message
    )
}

public func oauthErrorHtml(_ message: String, _ details: String? = nil) -> String {
    renderPage(
        title: "Authentication failed",
        heading: "Authentication failed",
        message: message,
        details: details
    )
}
