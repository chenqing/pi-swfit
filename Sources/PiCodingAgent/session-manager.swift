private func buildEntryIndex(_ entries: [SessionEntry], _ byId: [String: SessionEntry]?) -> [String: SessionEntry] {
    if let byId { return byId }
    var index: [String: SessionEntry] = [:]
    for entry in entries {
        index[entry.id] = entry
    }
    return index
}

/// `leafId`: `.none` = undefined (use the last entry), `.some(nil)` = null (empty path).
private func buildSessionPath(
    _ entries: [SessionEntry],
    _ leafId: String??,
    _ byId: [String: SessionEntry]?
) -> [SessionEntry] {
    let index = buildEntryIndex(entries, byId)
    var leaf: SessionEntry?
    if case .some(.none) = leafId {
        return []
    }
    if case .some(.some(let id)) = leafId, !id.isEmpty {
        leaf = index[id]
    }
    if leaf == nil { leaf = entries.last }
    guard let leaf else {
        return []
    }

    var path: [SessionEntry] = []
    var current: SessionEntry? = leaf
    while let entry = current {
        path.append(entry)
        current = entry.parentId.flatMap { $0.isEmpty ? nil : index[$0] }
    }
    path.reverse()
    return path
}

private func getSessionContextSettings(_ path: [SessionEntry]) -> (thinkingLevel: String, model: SessionModelRef?) {
    var thinkingLevel = "off"
    var model: SessionModelRef?

    for entry in path {
        if case .thinkingLevelChange(let e) = entry {
            thinkingLevel = e.thinkingLevel
        } else if case .modelChange(let e) = entry {
            model = SessionModelRef(provider: e.provider, modelId: e.modelId)
        } else if case .message(let e) = entry, case .assistant(let message) = e.message {
            model = SessionModelRef(provider: message.provider, modelId: message.model)
        }
    }

    return (thinkingLevel, model)
}

/**
 * Project one selected session entry into LLM/runtime messages.
 * Plain custom entries are display/state entries and do not participate in context.
 */
public func sessionEntryToContextMessages(_ entry: SessionEntry) -> [AgentMessage] {
    if case .message(let e) = entry {
        // Session files are parsed without validation; old versions, forks, or
        // hand-edited files can contain messages with null/missing content.
        // Swift: null/missing content is normalized to "" / [] when the entry is decoded.
        return [e.message]
    }
    if case .customMessage(let e) = entry {
        return [
            createCustomMessage(e.customType, e.content ?? .blocks([]), e.display, e.details, e.timestamp).agentMessage,
        ]
    }
    if case .branchSummary(let e) = entry, !e.summary.isEmpty {
        return [createBranchSummaryMessage(e.summary, e.fromId, e.timestamp).agentMessage]
    }
    if case .compaction(let e) = entry {
        let summary = createCompactionSummaryMessage(e.summary, e.tokensBefore, e.timestamp).agentMessage
        if let systemMessage = e.systemMessage { return [.system(systemMessage), summary] }
        return [summary]
    }
    return []
}

/**
 * Build the active, compaction-aware session entry list.
 *
 * This follows the current leaf path. If the path contains compaction entries,
 * the latest compaction is represented by the compaction entry itself, followed
 * by the kept entries starting at firstKeptEntryId and all entries after the
 * compaction entry. Older summarized entries are omitted.
 */
public func buildContextEntries(
    _ entries: [SessionEntry],
    _ leafId: String?? = .none,
    _ byId: [String: SessionEntry]? = nil
) -> [SessionEntry] {
    let path = buildSessionPath(entries, leafId, byId)
    var compaction: CompactionEntry?

    for entry in path {
        if case .compaction(let c) = entry {
            compaction = c
        }
    }

    guard let compaction else {
        return path
    }

    guard let compactionIdx = path.firstIndex(where: { $0.id == compaction.id }) else {
        return path
    }

    var contextEntries: [SessionEntry] = [.compaction(compaction)]
    var foundFirstKept = false
    for i in 0..<compactionIdx {
        let entry = path[i]
        if entry.id == compaction.firstKeptEntryId {
            foundFirstKept = true
        }
        var isSystemMessage = false
        if case .message(let e) = entry, e.message.role == "system" { isSystemMessage = true }
        if foundFirstKept && !isSystemMessage {
            contextEntries.append(entry)
        }
    }
    contextEntries.append(contentsOf: path[(compactionIdx + 1)...])
    return contextEntries
}

/**
 * Build the session context from entries using tree traversal.
 * If leafId is provided, walks from that entry to root.
 * Handles compaction and branch summaries along the path.
 */
private func projectContextEntry(_ entry: SessionEntry, _ edit: ContextEditEntry?) -> [AgentMessage] {
    let messages = sessionEntryToContextMessages(entry)
    guard let edit else { return messages }
    guard let replacement = edit.replacement else { return [] }

    return messages.map { message -> AgentMessage in
        let content = replacement.content
        switch message {
        case .user(var m):
            if let value = try? UserMessageContent(json: content) { m.content = value }
            return .user(m)
        case .assistant(var m):
            if case .string(let text) = content {
                m.content = [.text(TextContent(text: text))]
            } else if let blocks = content.arrayValue, let value = try? blocks.map(AssistantContent.init(json:)) {
                m.content = value
            }
            return .assistant(m)
        case .toolResult(var m):
            if case .string(let text) = content {
                m.content = [.text(TextContent(text: text))]
            } else if let blocks = content.arrayValue, let value = try? blocks.map(UserContent.init(json:)) {
                m.content = value
            }
            return .toolResult(m)
        case .custom(var custom) where custom.role == "custom":
            var payload = custom.payload.objectValue ?? JsonObject()
            payload["content"] = content
            custom.payload = .object(payload)
            return .custom(custom)
        default:
            return message
        }
    }
}

/** Build provenance-preserving, compaction-aware model context. */
public func buildSessionProjection(
    _ entries: [SessionEntry],
    _ leafId: String?? = .none,
    _ byId: [String: SessionEntry]? = nil
) -> SessionProjection {
    let path = buildSessionPath(entries, leafId, byId)
    let (thinkingLevel, model) = getSessionContextSettings(path)
    let contextEntries = buildContextEntries(entries, leafId, byId)
    var edits: [String: ContextEditEntry] = [:]
    for entry in contextEntries {
        if case .contextEdit(let edit) = entry { edits[edit.targetId] = edit }
    }
    let projectedEntries = contextEntries.enumerated().map { index, sourceEntry -> ProjectedSessionEntry in
        // buildContextEntries() may retain an older compaction entry because its
        // raw ID lies inside the newest retained range. Only the newest compaction
        // at index zero contributes a checkpoint and summary.
        var isOlderCompaction = false
        if case .compaction = sourceEntry, index > 0 { isOlderCompaction = true }
        return ProjectedSessionEntry(
            sourceEntry: sourceEntry,
            messages: isOlderCompaction ? [] : projectContextEntry(sourceEntry, edits[sourceEntry.id])
        )
    }
    return SessionProjection(
        entries: projectedEntries,
        messages: projectedEntries.flatMap(\.messages),
        thinkingLevel: thinkingLevel,
        model: model
    )
}

/** Build the finalized model context from the canonical session projection. */
public func buildSessionContext(
    _ entries: [SessionEntry],
    _ leafId: String?? = .none,
    _ byId: [String: SessionEntry]? = nil
) -> SessionContext {
    let projection = buildSessionProjection(entries, leafId, byId)
    return SessionContext(messages: projection.messages, thinkingLevel: projection.thinkingLevel, model: projection.model)
}

